CREATE TABLE IF NOT EXISTS public.payments (
  payment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id INTEGER NOT NULL UNIQUE REFERENCES public.orders(order_id) ON DELETE CASCADE,
  method TEXT NOT NULL CHECK (method IN ('GCash', 'COD')),
  idempotency_key TEXT NOT NULL UNIQUE,
  receipt_number TEXT NOT NULL UNIQUE,
  amount NUMERIC(10, 2) NOT NULL CHECK (amount >= 0),
  amount_collected NUMERIC(10, 2),
  is_flagged BOOLEAN NOT NULL DEFAULT FALSE,
  failure_reason TEXT,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'paid', 'collected', 'failed')),
  gateway_reference TEXT,
  checkout_session_id TEXT,
