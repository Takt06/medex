-- Public Reference Tables
CREATE POLICY "barangays_public_read" ON public.barangays FOR SELECT USING (TRUE);
CREATE POLICY "categories_public_read" ON public.product_categories FOR SELECT USING (TRUE);
CREATE POLICY "feedback_categories_public_read" ON public.feedback_categories FOR SELECT USING (TRUE);

-- Users
CREATE POLICY "users_read_self_or_admin" ON public.users
  FOR SELECT USING (auth_user_id = auth.uid() OR public.is_approved_admin());
CREATE POLICY "users_insert_self" ON public.users
  FOR INSERT WITH CHECK (auth_user_id = auth.uid());
CREATE POLICY "users_update_self_safe" ON public.users
  FOR UPDATE USING (auth_user_id = auth.uid() OR public.is_approved_admin());

-- Addresses (own addresses + approved merchant store locations visible publicly for map locator)
CREATE POLICY "addresses_read_own_or_approved_store_or_admin" ON public.addresses
  FOR SELECT USING (
    user_id = public.current_medex_user_id()
    OR public.is_approved_admin()
    OR EXISTS (
      SELECT 1
      FROM public.merchant_profiles mp
      JOIN public.users mu ON mu.user_id = mp.user_id
      WHERE mp.shop_address_id = addresses.address_id
        AND mu.status = 'approved'
    )
  );
CREATE POLICY "addresses_write_own" ON public.addresses
  FOR ALL USING (user_id = public.current_medex_user_id() OR public.is_approved_admin())
  WITH CHECK (user_id = public.current_medex_user_id() OR public.is_approved_admin());

-- Household flags & emergency contacts
CREATE POLICY "household_flags_own" ON public.household_flags
  FOR ALL USING (user_id = public.current_medex_user_id() OR public.is_approved_admin())
  WITH CHECK (user_id = public.current_medex_user_id() OR public.is_approved_admin());

CREATE POLICY "emergency_contacts_own" ON public.emergency_contacts
  FOR ALL USING (user_id = public.current_medex_user_id() OR public.is_approved_admin())
  WITH CHECK (user_id = public.current_medex_user_id() OR public.is_approved_admin());

-- Emergency alerts & verifications
CREATE POLICY "alerts_read_own_or_admin" ON public.emergency_alerts
  FOR SELECT USING (user_id = public.current_medex_user_id() OR public.is_approved_admin());
CREATE POLICY "alerts_insert_own" ON public.emergency_alerts
  FOR INSERT WITH CHECK (user_id = public.current_medex_user_id());
CREATE POLICY "alerts_update_own_or_admin" ON public.emergency_alerts
  FOR UPDATE USING (user_id = public.current_medex_user_id() OR public.is_approved_admin());

CREATE POLICY "alert_verifications_admin" ON public.alert_verifications
  FOR ALL USING (public.is_approved_admin())
  WITH CHECK (public.is_approved_admin());

-- Merchant Profiles & Hours (only approved merchants visible publicly; pending merchant sees own)
CREATE POLICY "merchants_read_approved_or_self_or_admin" ON public.merchant_profiles
  FOR SELECT USING (
    user_id = public.current_medex_user_id()
    OR public.is_approved_admin()
    OR EXISTS (SELECT 1 FROM public.users u WHERE u.user_id = merchant_profiles.user_id AND u.status = 'approved')
  );
CREATE POLICY "merchants_insert_self" ON public.merchant_profiles
  FOR INSERT WITH CHECK (user_id = public.current_medex_user_id() OR public.is_approved_admin());
CREATE POLICY "merchants_update_approved_self_or_admin" ON public.merchant_profiles
  FOR UPDATE USING (
    (user_id = public.current_medex_user_id() AND public.current_medex_status() = 'approved')
    OR public.is_approved_admin()
  );

CREATE POLICY "merchant_hours_read" ON public.merchant_hours
  FOR SELECT USING (
    merchant_id = public.current_medex_user_id()
    OR public.is_approved_admin()
