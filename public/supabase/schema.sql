  confirmation_code TEXT NOT NULL,
  code_attempts INTEGER NOT NULL DEFAULT 0,
  is_flagged_for_admin BOOLEAN NOT NULL DEFAULT FALSE,
  rider_lat DOUBLE PRECISION,
  rider_lng DOUBLE PRECISION,
