-- 1. CORE TABLES
-- ----------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.barangays (
  barangay_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  city TEXT NOT NULL DEFAULT 'Olongapo City',
  province TEXT NOT NULL DEFAULT 'Zambales',
  region TEXT NOT NULL DEFAULT 'Region III'
);

CREATE TABLE IF NOT EXISTS public.users (
  user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  auth_user_id UUID UNIQUE REFERENCES auth.users(id) ON DELETE SET NULL,
  role TEXT NOT NULL CHECK (role IN ('resident', 'merchant', 'rider', 'admin')),
  phone_number TEXT NOT NULL UNIQUE,
  email TEXT NOT NULL UNIQUE,
  first_name TEXT NOT NULL,
  last_name TEXT NOT NULL,
  date_of_birth DATE NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected', 'suspended')),
  status_reason TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_users_auth_user_id ON public.users (auth_user_id);
CREATE INDEX IF NOT EXISTS idx_users_role_status ON public.users (role, status);

CREATE TABLE IF NOT EXISTS public.addresses (
  address_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
  barangay_id INTEGER NOT NULL REFERENCES public.barangays(barangay_id),
  recipient_name TEXT NOT NULL,
  recipient_phone TEXT NOT NULL,
  street TEXT NOT NULL,
  landmark TEXT,
  delivery_instructions TEXT,
  latitude DOUBLE PRECISION NOT NULL,
  longitude DOUBLE PRECISION NOT NULL,
  is_primary BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_addresses_user_id ON public.addresses (user_id);

CREATE TABLE IF NOT EXISTS public.household_flags (
  user_id INTEGER PRIMARY KEY REFERENCES public.users(user_id) ON DELETE CASCADE,
  has_senior BOOLEAN NOT NULL DEFAULT FALSE,
  has_pwd BOOLEAN NOT NULL DEFAULT FALSE,
  has_young_child BOOLEAN NOT NULL DEFAULT FALSE,
  has_pregnant_member BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS public.emergency_contacts (
  contact_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
  contact_name TEXT NOT NULL,
  relationship TEXT NOT NULL,
  phone_number TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.emergency_alerts (
  alert_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reference_code TEXT NOT NULL UNIQUE,
  idempotency_key TEXT NOT NULL UNIQUE,
  user_id INTEGER NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
  category TEXT NOT NULL DEFAULT '911_general' CHECK (category IN ('911_general')),
  handoff_mode TEXT CHECK (handoff_mode IN ('mobile_dialer', 'desktop_qr')),
  address_id INTEGER NOT NULL REFERENCES public.addresses(address_id),
  address_snapshot TEXT NOT NULL,
  barangay_name TEXT NOT NULL,
  latitude DOUBLE PRECISION NOT NULL,
  longitude DOUBLE PRECISION NOT NULL,
  status TEXT NOT NULL DEFAULT 'submitted' CHECK (
    status IN ('queued_offline', 'submitted', 'received', 'verified', 'resolved', 'cancelled', 'escalated')
  ),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  cancelled_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_emergency_alerts_user ON public.emergency_alerts (user_id, created_at DESC);

CREATE TABLE IF NOT EXISTS public.alert_verifications (
  verification_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  alert_id INTEGER NOT NULL UNIQUE REFERENCES public.emergency_alerts(alert_id) ON DELETE CASCADE,
  decision TEXT NOT NULL CHECK (decision IN ('genuine', 'false_alarm', 'accidental_press')),
  verified_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  verified_by_id INTEGER NOT NULL REFERENCES public.users(user_id),
  verified_by_name TEXT NOT NULL,
  notes TEXT NOT NULL DEFAULT ''
);

-- 2. PHARMACY STOREFRONT & INVENTORY
-- ----------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.product_categories (
  category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE CHECK (
    name IN ('Medicines', 'First Aid', 'Hygiene', 'Baby Care', 'Masks & PPE', 'Equipment')
  )
);

CREATE TABLE IF NOT EXISTS public.merchant_profiles (
  merchant_id INTEGER PRIMARY KEY REFERENCES public.users(user_id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL UNIQUE REFERENCES public.users(user_id) ON DELETE CASCADE,
  shop_name TEXT NOT NULL,
  shop_address_id INTEGER NOT NULL REFERENCES public.addresses(address_id),
  is_pharmacist BOOLEAN NOT NULL DEFAULT TRUE,
  pharmacist_name TEXT NOT NULL,
  pharmacist_license_no TEXT NOT NULL,
  is_24_hours BOOLEAN NOT NULL DEFAULT FALSE,
  is_temporarily_closed BOOLEAN NOT NULL DEFAULT FALSE,
  contact_no TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.merchant_hours (
  hours_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  merchant_id INTEGER NOT NULL REFERENCES public.merchant_profiles(merchant_id) ON DELETE CASCADE,
  day_of_week SMALLINT NOT NULL CHECK (day_of_week BETWEEN 0 AND 6),
  opens_at TEXT NOT NULL,
  closes_at TEXT NOT NULL,
  is_closed BOOLEAN NOT NULL DEFAULT FALSE,
  UNIQUE (merchant_id, day_of_week)
);

CREATE TABLE IF NOT EXISTS public.products (
  product_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  merchant_id INTEGER NOT NULL REFERENCES public.merchant_profiles(merchant_id) ON DELETE CASCADE,
  category_id INTEGER NOT NULL REFERENCES public.product_categories(category_id),
  name TEXT NOT NULL,
  dosage_strength TEXT,
  description TEXT NOT NULL DEFAULT '',
  image_path TEXT NOT NULL DEFAULT '',
  unit TEXT NOT NULL,
  purchase_limit INTEGER NOT NULL DEFAULT 5 CHECK (purchase_limit > 0),
  is_listed BOOLEAN NOT NULL DEFAULT TRUE,
  requires_prescription BOOLEAN NOT NULL DEFAULT FALSE,
  regular_price NUMERIC(10, 2) NOT NULL CHECK (regular_price >= 0),
  stock_quantity INTEGER NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0),
  low_stock_threshold INTEGER NOT NULL DEFAULT 10 CHECK (low_stock_threshold >= 0),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_products_merchant ON public.products (merchant_id, is_listed);

-- 3. ORDERS, PRESCRIPTIONS, PAYMENTS & DELIVERY
-- ----------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.orders (
  order_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_code TEXT NOT NULL UNIQUE,
  idempotency_key TEXT NOT NULL UNIQUE,
  resident_id INTEGER NOT NULL REFERENCES public.users(user_id),
  merchant_id INTEGER NOT NULL REFERENCES public.merchant_profiles(merchant_id),
  alert_id INTEGER REFERENCES public.emergency_alerts(alert_id),
  address_id INTEGER NOT NULL REFERENCES public.addresses(address_id),
  delivery_address_snapshot TEXT NOT NULL,
  recipient_name TEXT NOT NULL,
  recipient_phone TEXT NOT NULL,
  rider_note TEXT,
  subtotal NUMERIC(10, 2) NOT NULL CHECK (subtotal >= 0),
  delivery_fee NUMERIC(10, 2) NOT NULL CHECK (delivery_fee >= 0),
  total_amount NUMERIC(10, 2) NOT NULL CHECK (total_amount >= 0),
  status TEXT NOT NULL CHECK (
    status IN (
      'awaiting_prescription_review',
      'pending',
      'placed',
      'preparing',
      'ready_for_pickup',
      'out_for_delivery',
      'delivered',
      'cancelled'
    )
  ),
  cancel_reason TEXT,
  placed_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_orders_resident ON public.orders (resident_id, placed_at DESC);
CREATE INDEX IF NOT EXISTS idx_orders_merchant ON public.orders (merchant_id, placed_at DESC);

CREATE TABLE IF NOT EXISTS public.order_items (
  order_item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id INTEGER NOT NULL REFERENCES public.orders(order_id) ON DELETE CASCADE,
  product_id INTEGER NOT NULL REFERENCES public.products(product_id),
  merchant_id INTEGER NOT NULL REFERENCES public.merchant_profiles(merchant_id),
  product_name TEXT NOT NULL,
  unit TEXT NOT NULL,
  requires_prescription BOOLEAN NOT NULL DEFAULT FALSE,
  unit_price NUMERIC(10, 2) NOT NULL CHECK (unit_price >= 0),
  quantity INTEGER NOT NULL CHECK (quantity > 0)
);

CREATE TABLE IF NOT EXISTS public.order_status_history (
  history_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id INTEGER NOT NULL REFERENCES public.orders(order_id) ON DELETE CASCADE,
  status TEXT NOT NULL,
  note TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.prescriptions (
  prescription_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id INTEGER NOT NULL UNIQUE REFERENCES public.orders(order_id) ON DELETE CASCADE,
  resident_id INTEGER NOT NULL REFERENCES public.users(user_id),
  merchant_id INTEGER NOT NULL REFERENCES public.merchant_profiles(merchant_id),
  patient_name TEXT NOT NULL,
  doctor_name TEXT NOT NULL,
  license_no TEXT NOT NULL,
  date_issued DATE NOT NULL,
  valid_until DATE,
  file_name TEXT NOT NULL,
  file_type TEXT NOT NULL CHECK (file_type IN ('jpg', 'png', 'pdf')),
  file_preview_url TEXT NOT NULL,
  storage_path TEXT,
  status TEXT NOT NULL DEFAULT 'pending_review' CHECK (status IN ('pending_review', 'approved', 'rejected')),
  reject_reason TEXT,
  remarks TEXT,
  reviewed_by TEXT,
  reviewed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
